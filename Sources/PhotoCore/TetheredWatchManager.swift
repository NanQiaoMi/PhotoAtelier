import Foundation
import Dispatch

/// Configuration for tethered shooting hot folder monitoring.
public struct TetheredWatchConfiguration: Codable, Equatable {
    /// Directory URL to monitor for incoming captured photos.
    public var folderURL: URL?
    /// Whether to scan nested subdirectories inside the watch folder.
    public var includeSubfolders: Bool
    /// Whether to automatically select and view the newest photo when it arrives.
    public var autoSelectLatest: Bool
    /// Stability settling delay in seconds: ensures camera utility has flushed the
    /// entire RAW/JPEG file to disk before PhotoAtelier begins reading it.
    public var fileStabilityDelay: TimeInterval

    public init(folderURL: URL? = nil,
                includeSubfolders: Bool = false,
                autoSelectLatest: Bool = true,
                fileStabilityDelay: TimeInterval = 0.4) {
        self.folderURL = folderURL
        self.includeSubfolders = includeSubfolders
        self.autoSelectLatest = autoSelectLatest
        self.fileStabilityDelay = fileStabilityDelay
    }
}

/// Operational state of the tethered watch engine.
public enum TetheredWatchState: Equatable {
    case idle
    case watching(URL)
    case paused
    case error(String)

    public var isWatching: Bool {
        if case .watching = self { return true }
        return false
    }

    public var folderURL: URL? {
        if case .watching(let url) = self { return url }
        return nil
    }

    public var title: String {
        switch self {
        case .idle: return "未监视"
        case .watching(let url): return "正在监视：\(url.lastPathComponent)"
        case .paused: return "监视已暂停"
        case .error(let message): return "错误：\(message)"
        }
    }
}

/// Native file-system monitoring engine for studio tethered shooting.
///
/// Designed to monitor watch folders generated by tethering utilities
/// (Canon EOS Utility, Sony Imaging Edge, Nikon NX Tether, Fujifilm X Acquire,
/// Capture One, etc.). Uses macOS `DispatchSourceFileSystemObject` for real-time
/// directory events plus a settling poll timer to ensure large multi-megabyte
/// RAW/JPEG files are fully flushed to disk before notifying callers.
public final class TetheredWatchManager {

    public private(set) var state: TetheredWatchState = .idle {
        didSet {
            let newState = state
            DispatchQueue.main.async { [weak self] in
                guard let self else { return }
                self.onStateChange?(newState)
            }
        }
    }

    public var onNewPhotos: (([URL]) -> Void)?
    public var onStateChange: ((TetheredWatchState) -> Void)?

    private let queue = DispatchQueue(label: "com.atelier.tethered-watch", qos: .utility)
    private var source: DispatchSourceFileSystemObject?
    private var timer: DispatchSourceTimer?
    private var fileDescriptor: Int32 = -1
    private var knownURLs: Set<URL> = []
    private var pendingCandidateSizes: [URL: (size: Int64, seenCount: Int)] = [:]
    private var activeConfig: TetheredWatchConfiguration?

    public init() {}

    deinit {
        stop()
    }

    /// Starts monitoring the designated folder. Existing photos in the folder
    /// are recorded into the known set so they do not trigger spurious arrivals.
    public func start(configuration: TetheredWatchConfiguration) throws {
        stop()

        guard let folderURL = configuration.folderURL else {
            state = .error("未指定监视文件夹路径")
            throw AtelierError.invalidConfiguration("未指定联机拍摄监视文件夹路径。")
        }

        var isDir: ObjCBool = false
        guard FileManager.default.fileExists(atPath: folderURL.path, isDirectory: &isDir), isDir.boolValue else {
            state = .error("文件夹不存在或不是有效目录：\(folderURL.lastPathComponent)")
            throw AtelierError.invalidConfiguration("监视文件夹不存在：\(folderURL.path)")
        }

        let fd = open(folderURL.path, O_EVTONLY)
        guard fd >= 0 else {
            state = .error("无法打开文件夹以建立事件监视：\(folderURL.lastPathComponent)")
            throw AtelierError.invalidConfiguration("打开监视文件夹句柄失败：errno=\(errno)")
        }

        self.fileDescriptor = fd
        self.activeConfig = configuration
        self.knownURLs = scanExistingURLs(in: folderURL, includeSubfolders: configuration.includeSubfolders)
        self.pendingCandidateSizes.removeAll()

        let dirSource = DispatchSource.makeFileSystemObjectSource(
            fileDescriptor: fd,
            eventMask: [.write, .extend, .attrib, .link],
            queue: queue
        )

        dirSource.setEventHandler { [weak self] in
            self?.checkDirectoryForNewFiles()
        }

        dirSource.setCancelHandler {
            close(fd)
        }

        self.source = dirSource
        dirSource.resume()

        // Background poll timer (runs every 0.5s to ensure settle verification and catch
        // atomic renames that don't trigger directory descriptor write events)
        let pollTimer = DispatchSource.makeTimerSource(queue: queue)
        pollTimer.schedule(deadline: .now() + 0.5, repeating: 0.5)
        pollTimer.setEventHandler { [weak self] in
            self?.checkDirectoryForNewFiles()
        }
        self.timer = pollTimer
        pollTimer.resume()

        state = .watching(folderURL)
    }

    /// Stops monitoring and releases open file descriptors.
    public func stop() {
        if let timer {
            timer.cancel()
            self.timer = nil
        }
        if let source {
            source.cancel()
            self.source = nil
        }
        fileDescriptor = -1
        pendingCandidateSizes.removeAll()
        activeConfig = nil
        if state != .idle {
            state = .idle
        }
    }

    /// Pauses file event processing.
    public func pause() {
        guard case .watching = state else { return }
        source?.suspend()
        timer?.suspend()
        state = .paused
    }

    /// Resumes file event processing.
    public func resume() {
        guard state == .paused, let config = activeConfig, let url = config.folderURL else { return }
        source?.resume()
        timer?.resume()
        state = .watching(url)
    }

    /// Records URLs as already known so they will not trigger new-photo callbacks.
    public func recordKnownURLs(_ urls: [URL]) {
        queue.async { [weak self] in
            guard let self else { return }
            for url in urls {
                self.knownURLs.insert(url.standardizedFileURL)
            }
        }
    }

    /// Queries whether a given URL is already recorded in the known set.
    public func isKnown(_ url: URL) -> Bool {
        queue.sync {
            knownURLs.contains(url.standardizedFileURL)
        }
    }

    /// Total count of known photos currently tracked.
    public var knownCount: Int {
        queue.sync {
            knownURLs.count
        }
    }

    /// Manually triggers a scan of the monitored folder.
    public func manualScan() {
        queue.async { [weak self] in
            self?.checkDirectoryForNewFiles()
        }
    }

    // MARK: - Internal Engine

    private func scanExistingURLs(in folder: URL, includeSubfolders: Bool) -> Set<URL> {
        let options: FileManager.DirectoryEnumerationOptions = includeSubfolders
            ? [.skipsHiddenFiles, .skipsPackageDescendants]
            : [.skipsHiddenFiles, .skipsPackageDescendants, .skipsSubdirectoryDescendants]

        guard let enumerator = FileManager.default.enumerator(
            at: folder,
            includingPropertiesForKeys: [.isRegularFileKey, .fileSizeKey],
            options: options
        ) else {
            return []
        }

        var result: Set<URL> = []
        for case let fileURL as URL in enumerator {
            if PhotoLoader.isSupportedCandidate(fileURL) {
                result.insert(fileURL.standardizedFileURL)
            }
        }
        return result
    }

    private func checkDirectoryForNewFiles() {
        guard let config = activeConfig, let folderURL = config.folderURL else { return }

        let currentFound = scanExistingURLs(in: folderURL, includeSubfolders: config.includeSubfolders)
        let newlyDiscovered = currentFound.subtracting(knownURLs)

        var readyToReport: [URL] = []

        // Evaluate file stability
        for url in newlyDiscovered {
            let path = url.path
            guard let attrs = try? FileManager.default.attributesOfItem(atPath: path),
                  let fileSize = attrs[.size] as? Int64 else {
                continue
            }

            if fileSize <= 0 {
                // File is currently empty, still being allocated by camera
                pendingCandidateSizes[url] = (size: 0, seenCount: 1)
                continue
            }

            if config.fileStabilityDelay <= 0 {
                readyToReport.append(url)
                knownURLs.insert(url)
                pendingCandidateSizes.removeValue(forKey: url)
                continue
            }

            let modDate = attrs[.modificationDate] as? Date ?? Date()
            let timeSinceModified = Date().timeIntervalSince(modDate)

            if let pending = pendingCandidateSizes[url] {
                if pending.size == fileSize {
                    // Size has stayed stable over at least 1 check interval, or file hasn't been written to for fileStabilityDelay
                    if pending.seenCount >= 1 || timeSinceModified >= config.fileStabilityDelay {
                        readyToReport.append(url)
                        knownURLs.insert(url)
                        pendingCandidateSizes.removeValue(forKey: url)
                    } else {
                        pendingCandidateSizes[url] = (size: fileSize, seenCount: pending.seenCount + 1)
                    }
                } else {
                    // File size is still growing
                    pendingCandidateSizes[url] = (size: fileSize, seenCount: 0)
                }
            } else {
                if timeSinceModified >= config.fileStabilityDelay {
                    // File was already written and unmodified for longer than the stability delay
                    readyToReport.append(url)
                    knownURLs.insert(url)
                } else {
                    // First time seen: record size and wait for settling check
                    pendingCandidateSizes[url] = (size: fileSize, seenCount: 0)
                }
            }
        }

        if !readyToReport.isEmpty {
            // Sort deterministically by path
            let sorted = readyToReport.sorted { $0.path < $1.path }
            DispatchQueue.main.async { [weak self] in
                self?.onNewPhotos?(sorted)
            }
        }
    }
}
